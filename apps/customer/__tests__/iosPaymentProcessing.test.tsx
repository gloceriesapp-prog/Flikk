import type { ComponentProps } from 'react';
import { act, render, waitFor } from '@testing-library/react-native';
import { PaymentProcessingScreen } from '../src/screens/payment-processing/PaymentProcessingScreen';
import { pollOrderPaid } from '../src/payments/pollOrderPaid';
import { openRazorpayCheckout } from '../src/payments/openRazorpayCheckout';
import { dismissIosUpiCheckout } from '../src/payments/iosUpiCheckout';
import { clearCommittedAttempt } from '../src/features/checkout-recovery/attemptStorage';
import { verifyPayment } from '../src/api/payments';
const mockReplace = jest.fn(), mockClear = jest.fn();
const mockItems = [{ id: 'p', productId: 'p', quantity: 1 }];
jest.mock('../src/payments/pollOrderPaid', () => ({ pollOrderPaid: jest.fn(), paymentCheckDeadline: () => Date.now() + 120000 }));
jest.mock('../src/payments/openRazorpayCheckout', () => ({ openRazorpayCheckout: jest.fn() }));
jest.mock('../src/payments/upiIntent', () => ({ launchUpiIntent: jest.fn() }));
jest.mock('../src/payments/iosUpiCheckout', () => ({ dismissIosUpiCheckout: jest.fn() }));
jest.mock('../src/api/payments', () => ({ verifyPayment: jest.fn(), rememberPaymentMethod: jest.fn(async () => {}) }));
jest.mock('../src/features/checkout-recovery/attemptStorage', () => ({ clearCommittedAttempt: jest.fn(async () => {}) }));
jest.mock('../src/store/useAuthStore', () => ({ useAuthStore: { getState: () => ({ sessionEpoch: 1 }) } }));
jest.mock('../src/store/useCartStore', () => ({ useCartStore: Object.assign((select: (state: unknown) => unknown) => select({ clear: mockClear }), { getState: () => ({ items: mockItems, preorder: null }) }) }));
jest.mock('../src/store/cartIdentity', () => ({ cartPurchaseSignature: (items: unknown) => JSON.stringify(items) }));
const target = { orderId: 'existing-order' };
const props = { route: { params: { target, amount: 1, paymentMethod: 'upi_app:gpay', appName: 'Google Pay', iosUpiOrder: { providerOrderId: 'order_existing' }, order: { orderId: 'existing-order', orderNumber: 'GLO-test' }, items: mockItems, deliveryAddress: 'Saved address' } }, navigation: { replace: mockReplace, navigate: jest.fn() } } as unknown as ComponentProps<typeof PaymentProcessingScreen>;
beforeEach(() => { jest.clearAllMocks(); });
test('server-confirmed payment shows confirmation even when the native callback never arrives', async () => {
  jest.mocked(openRazorpayCheckout).mockImplementation(() => new Promise(() => {}));
  jest.mocked(pollOrderPaid).mockResolvedValue(true);
  const view = await render(<PaymentProcessingScreen {...props} />);
  await waitFor(() => expect(mockReplace).toHaveBeenCalledWith('OrderPlaced', expect.objectContaining({ orderId: 'existing-order', paid: true })));
  expect(clearCommittedAttempt).toHaveBeenCalledWith(target);
  expect(mockClear).toHaveBeenCalledTimes(1);
  expect(verifyPayment).not.toHaveBeenCalled();
  await view.unmount(); expect(dismissIosUpiCheckout).toHaveBeenCalled();
});
test('a native error cannot mark a payment failed or clear an unpaid cart', async () => {
  let resolve!: (paid: boolean) => void;
  jest.mocked(openRazorpayCheckout).mockRejectedValue(new Error('Gateway cancellation'));
  jest.mocked(pollOrderPaid).mockImplementation(() => new Promise(done => { resolve = done; }));
  const view = await render(<PaymentProcessingScreen {...props} />);
  await waitFor(() => expect(view.getByText('We’re checking your payment status. Please don’t pay again.')).toBeTruthy());
  await act(() => { resolve(false); });
  expect(mockReplace).toHaveBeenCalledWith('PaymentRecovery', { target });
  expect(mockClear).not.toHaveBeenCalled();
  await view.unmount();
});
