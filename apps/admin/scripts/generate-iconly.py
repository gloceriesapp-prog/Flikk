#!/usr/bin/env python3
"""Generate typed React icons from the original, locally stored Iconly SVGs."""
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

BASE = pathlib.Path(__file__).resolve().parents[1] / 'src/components/icons'
ALLOWED = {'svg', 'g', 'path', 'circle', 'ellipse', 'line', 'polyline', 'polygon', 'rect', 'title', 'desc'}
CAMEL = {'fill-rule': 'fillRule', 'clip-rule': 'clipRule', 'stroke-width': 'strokeWidth',
         'stroke-linecap': 'strokeLinecap', 'stroke-linejoin': 'strokeLinejoin',
         'stroke-miterlimit': 'strokeMiterlimit', 'stroke-dasharray': 'strokeDasharray',
         'stroke-dashoffset': 'strokeDashoffset', 'fill-opacity': 'fillOpacity',
         'stroke-opacity': 'strokeOpacity'}

def tag(el):
    return el.tag.split('}')[-1]

def jsx(el):
    name = tag(el)
    if name not in ALLOWED:
        raise ValueError(f'Unsupported SVG element: {name}')
    if name in {'title', 'desc'}:
        return ''
    attrs = []
    for key, value in el.attrib.items():
        if key in {'id', 'version', 'draggable'}:
            continue
        if key.startswith('on') or key.startswith('{') or key in {'style', 'href'} or 'url(' in value:
            raise ValueError(f'Unsafe SVG attribute: {key}')
        # Icons inherit the surrounding colour, including filled rating stars.
        if key == 'fill' and value == 'none' and name == 'g':
            continue
        if key in {'fill', 'stroke'} and value.lower() in {'black', '#000000', '#000'}:
            value = 'currentColor'
        if key == 'stroke-width' and value not in {'0', '1'}:
            attrs.append(f'strokeWidth={{strokeWidth ?? {json.dumps(value)}}}')
        else:
            attrs.append(f'{CAMEL.get(key, key)}={json.dumps(value)}')
    opening = f'<{name}' + (' ' + ' '.join(attrs) if attrs else '')
    children = ''.join(jsx(child) for child in el)
    return opening + ('>' + children + f'</{name}>' if children else ' />')

manifest = json.loads((BASE / 'manifest.json').read_text())
lines = [
    "'use client';", '',
    '// Generated by scripts/generate-iconly.py. Edit the manifest and original assets instead.',
    "import { createIcon } from './Icon';",
    "export type { IconComponent, IconProps } from './Icon';", '',
]
by_file = {}
for alias, entry in manifest.items():
    if not re.fullmatch(r'[A-Z][A-Za-z0-9]*', alias):
        raise ValueError(f'Invalid export: {alias}')
    if entry['file'] in by_file:
        lines.append(f'export const {alias} = {by_file[entry["file"]]};')
        continue
    root = ET.fromstring((BASE / 'assets' / entry['file']).read_text())
    if tag(root) != 'svg':
        raise ValueError('Expected an SVG root')
    viewbox = root.attrib.get('viewBox', '0 0 24 24')
    if not re.fullmatch(r'[-0-9. ]+', viewbox):
        raise ValueError('Invalid viewBox')
    children = ''.join(jsx(child) for child in root)
    # Keep the factory argument even for filled icons; no unused-parameter warning.
    lines.append(f'export const {alias} = /* #__PURE__ */ createIcon({json.dumps(entry["name"])}, {json.dumps(viewbox)}, (strokeWidth) => (<>{children}</>));')
    by_file[entry['file']] = alias
result = '\n'.join(lines) + '\n'
target = BASE / 'index.tsx'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != result:
        sys.exit('Iconly components are stale. Run npm run icons:generate.')
else:
    target.write_text(result)
print(f'Iconly: {len(manifest)} exports, {len(by_file)} original assets verified.')
